#!/usr/bin/env bash
# Regenerates docs/DEMO.md from REAL runs of the built nova executable (build/nova). Nothing is typed in by hand:
# every transcript below is captured output and exit code. SmartPass timings differ from run to run.
# Usage: scripts/make_demo.sh [path-to-nova]   (default build/nova)
set -u
cd "$(dirname "$0")/.."
export PATH="/c/Program Files/CMake/bin:/c/MinGW/bin:$PATH"
NOVA="${1:-build/nova}"
[ -x "$NOVA" ] || NOVA="build/nova.exe"
OUT=docs/DEMO.md
TMP="build/demo-run"
rm -rf "$TMP"
mkdir -p "$TMP"

run() {  # run <command...>: prints a fenced transcript with exit code
  echo '```'
  echo "\$ $*"
  "$@" 2>&1
  echo "[exit $?]"
  echo '```'
  echo
}

{
  echo "# NOVA demonstration (generated)"
  echo
  echo "Generated by \`scripts/make_demo.sh\` on $(date -u +%Y-%m-%dT%H:%MZ) with \`$($NOVA --version)\`. Every block below is captured output of a real run."
  echo "SmartPass timings are specific to that run and machine; they are not results (see report/report.md for the evaluated data)."
  echo
  echo "## 1. NOVA Script: tokens, AST, TAC, execution, optimization"
  echo
  echo "Source (\`examples/basic.nova\`):"
  echo '```'
  cat examples/basic.nova
  echo '```'
  echo
  run $NOVA tokens examples/basic.nova
  run $NOVA ast examples/basic.nova
  run $NOVA tac examples/basic.nova
  run $NOVA run examples/basic.nova
  echo "Optimizer (\`examples/optimize_demo.nova\`), every pass that changed the program:"
  echo
  echo '```'
  cat examples/optimize_demo.nova
  echo '```'
  echo
  run $NOVA opt examples/optimize_demo.nova --show-all
  echo "## 2. Invalid programs are rejected before any code is generated"
  echo
  run $NOVA tokens examples/invalid_char.nova
  run $NOVA ast examples/invalid_syntax.nova
  run $NOVA tac examples/undeclared.nova
  run $NOVA tac examples/duplicate.nova
  echo "Division by zero is a runtime error (output before it is kept); the optimizer must not hide it:"
  echo
  run $NOVA run examples/divzero.nova
  run $NOVA opt examples/divzero.nova
  echo "Unknown commands and options are usage errors:"
  echo
  run $NOVA frobnicate
  run $NOVA opt examples/basic.nova --passes=nonsense
  echo "## 3. Benchmark lab and SmartPass (real, small run: stencil, budget 3, 5 repetitions, pinned CPU)"
  echo
  run $NOVA bench list
  run $NOVA tune stencil --budget=3 --strategy=adaptive --seed=1 --reps=5 --warmup=1 --pilot-reps=3 --affinity=10 --high-priority --id=demo-tune --out="$TMP/demo-tune"
  run $NOVA explain "$TMP/demo-tune"
  run $NOVA tune matmul --budget=2 --size=320
  echo "(The last command is refused on purpose: 320 is a registered holdout size and tuning may not use it.)"
} > "$OUT"
echo "wrote $OUT"
